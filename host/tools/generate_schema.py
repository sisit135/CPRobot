"""Generate the flash catalog, protobuf descriptor, and source pages together."""
import argparse
import json
import math
from pathlib import Path
import re
import struct
import subprocess
import tempfile
import zlib
from google.protobuf import descriptor_pb2

ROOT = Path(__file__).resolve().parents[2]
HEADER = "// Generated by host/tools/generate_schema.py. SPDX-License-Identifier: GPL-3.0-only\n"
TYPES = {"float": (0, "float"), "uint32": (1, "uint32"), "bool": (2, "bool")}


def f32(value):
    return struct.unpack("<f", struct.pack("<f", value))[0]


def literal(value):
    text = format(f32(value), ".9g")
    if "." not in text and "e" not in text:
        text += ".0"
    return text + "f"


def array(name, data):
    rows = [", ".join(str(byte) for byte in data[i:i + 24]) for i in range(0, len(data), 24)]
    return "inline constexpr uint8_t " + name + "[] = {\n  " + ",\n  ".join(rows) + "\n};\n"


def generate(root=ROOT):
    manifest = json.loads((root / "proto/flash_settings.json").read_text())
    fields, sources = manifest["fields"], manifest["sources"]
    # 28-byte header/CRC plus binary32 values must fit the 512-byte inline file.
    if manifest["format"] != 2 or not 1 <= len(fields) <= 121:
        raise ValueError("Unsupported flash catalog format/count")
    keys, names, bindings = set(), set(), set()
    for field in fields:
        key, name, kind, binding = (field[k] for k in ("key", "name", "type", "binding"))
        if (not isinstance(key, int) or not 1 <= key < 19000 or key in keys or
                not re.fullmatch(r"[a-z][a-z0-9_]{0,47}", name) or name in names or
                kind not in TYPES or binding in bindings or
                not re.fullmatch(r"(?:feature|rhr|tape)\.[a-z][a-z0-9_]*|motor\.[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)?|gyro_zero|color\.[0-3]\.[a-z]+", binding)):
            raise ValueError(f"Invalid/duplicate flash field: {field}")
        keys.add(key); names.add(name); bindings.add(binding)
        expected_name = ("gyro_zero_rps" if binding == "gyro_zero" else
                         "legacy_color_" + binding[6:].replace(".", "_") if binding.startswith("color.") else
                         binding.replace(".", "_"))
        if name != expected_name:
            raise ValueError(f"Schema name does not match runtime binding: {name}")
        values = [field[k] for k in ("minimum", "maximum", "default")]
        if not all(isinstance(v, (int, float)) and math.isfinite(v) for v in values):
            raise ValueError(f"Nonfinite field limits: {name}")
        lo, hi, initial = map(f32, values)
        if not lo <= initial <= hi or lo >= hi:
            raise ValueError(f"Default outside bounds: {name}")
        if kind != "float" and (not all(float(v).is_integer() for v in values) or lo < 0):
            raise ValueError(f"Invalid integer field: {name}")
        if kind == "bool" and (lo, hi) != (0, 1):
            raise ValueError(f"Invalid boolean field: {name}")
        source = sources[str(field["source_id"])]
        if len(source) > 64 or len(field["group"]) > 24 or not (root / "fw/robot_sf/include" / source).is_file():
            raise ValueError(f"Missing/oversized source reference: {source}")
    fields = sorted(fields, key=lambda f: f["key"])
    for binding in ("tape.black_max", "tape.white_min", "gyro_zero"):
        if binding not in bindings:
            raise ValueError(f"Missing required sensor binding: {binding}")
    for field in fields:
        binding = field["binding"]
        if binding.startswith("tape.") and (field["type"] != "uint32" or field["maximum"] > 65535):
            raise ValueError("Tape thresholds must fit uint16")
        if binding == "gyro_zero" and field["type"] != "float":
            raise ValueError("Gyro zero must be binary32")
        if binding.startswith("color."):
            _, slot, component = binding.split(".")
            components = ("enabled", "red", "green", "blue", "geometry", "gx", "gy")
            if component not in components or field["key"] != 100 + 10 * int(slot) + components.index(component):
                raise ValueError("Legacy color keys are stable compatibility identifiers")
    if sum(f["binding"].startswith("color.") for f in fields) != 28:
        raise ValueError("All legacy color slots must remain present")
    identity = {"format": manifest["format"], "fields": [
        {key: field[key] for key in ("key", "name", "type", "binding")} for field in fields]}
    signature = zlib.crc32(json.dumps(identity, sort_keys=True, separators=(",", ":")).encode())
    proto = HEADER + '\nsyntax = "proto3";\npackage axi.remote.v1;\n\n'
    proto += "// Field numbers are the stable RemoteRequest/FieldSpec keys.\n"
    proto += "// Bounds and factory values are advertised by LIST_FIELDS.\nmessage FlashSettings {\n"
    for field in fields:
        proto += f'  // {field["group"]}: {field["minimum"]}..{field["maximum"]}; factory {field["default"]}.\n'
        proto += f'  {TYPES[field["type"]][1]} {field["name"]} = {field["key"]};\n'
    proto += "}\n"
    catalog = HEADER + '#pragma once\n#include "remote/catalog_types.hpp"\n#include <array>\n#include <cstddef>\nnamespace remote {\n'
    catalog += f"inline constexpr std::size_t kFields = {len(fields)};\ninline constexpr uint32_t kCatalogSignature = 0x{signature:08x}u;\n"
    catalog += "inline constexpr std::array<Spec, kFields> kCatalog{{\n"
    for field in fields:
        source = sources[str(field["source_id"])]
        catalog += ('  {%d, %s, %s, %d, %s, %s, %s, %s, %d},\n' % (
            field["key"], json.dumps(field["name"]), json.dumps(field["group"]), TYPES[field["type"]][0],
            literal(field["minimum"]), literal(field["maximum"]), literal(field["default"]),
            json.dumps(source), field["source_id"]))
    catalog += "}};\n} // namespace remote\n"
    bindings_header = HEADER + '#pragma once\n#include "remote/settings.hpp"\n#include <type_traits>\nnamespace remote::generated {\n'
    for field in fields:
        if field["binding"] in ("tape.black_max", "tape.white_min", "gyro_zero"):
            name = field["binding"].replace(".", "_") + "_key"
            bindings_header += f'inline constexpr uint32_t {name} = {field["key"]};\n'
    for prefix, typename in (("feature", "nav::FeatureConfig"), ("rhr", "nav::RightHandConfig"),
                             ("motor", "motor::OpenLoopConfig")):
        for field in fields:
            if field["binding"].startswith(prefix + "."):
                member = field["binding"].split(".", 1)[1]
                integral = "true" if field["type"] != "float" else "false"
                bindings_header += (f'static_assert(std::is_integral_v<decltype({typename}{{}}.{member})> == {integral}, '
                                    f'"Flash type drift: {field["name"]}");\n')
                bindings_header += (f'static_assert({typename}{{}}.{member} == '
                                    f'static_cast<decltype({typename}{{}}.{member})>({literal(field["default"])}), '
                                    f'"Flash factory default drift: {field["name"]}");\n')
        function = "open_loop" if prefix == "motor" else prefix
        bindings_header += f"template <class Values> {typename} {function}(const Values &values) {{\n  {typename} result;\n"
        for index, field in enumerate(fields):
            if field["binding"].startswith(prefix + "."):
                member = field["binding"].split(".", 1)[1]
                bindings_header += f"  result.{member} = static_cast<decltype(result.{member})>(values[{index}]);\n"
        bindings_header += "  return result;\n}\n"
    bindings_header += "} // namespace remote::generated\n"
    with tempfile.TemporaryDirectory(prefix="ths-schema-") as staging:
        stage = Path(staging)
        (stage / "flash_settings.proto").write_text(proto)
        descriptor = stage / "robot.desc"
        subprocess.run(["protoc", "-I" + str(stage), "-I" + str(root / "proto"),
                        "--include_imports", "--descriptor_set_out=" + str(descriptor),
                        "telemetry.proto", "remote_config.proto", "flash_settings.proto"], check=True)
        data = descriptor.read_bytes()
    if not 0 < len(data) <= 65536:
        raise ValueError("Descriptor exceeds Android import bounds")
    desc = descriptor_pb2.FileDescriptorSet.FromString(data)
    settings = next(m for f in desc.file for m in f.message_type if m.name == "FlashSettings")
    actual = [(f.number, f.name, f.type) for f in settings.field]
    pb_types = {"float": 2, "uint32": 13, "bool": 8}
    expected = [(f["key"], f["name"], pb_types[f["type"]]) for f in fields]
    if actual != expected:
        raise ValueError("Flash descriptor/catalog mismatch")
    blobs = HEADER + "#pragma once\n#include <cstdint>\n#include <cstddef>\nnamespace remote {\n"
    for source_id, name in sorted(sources.items(), key=lambda item: int(item[0])):
        content = (root / "fw/robot_sf/include" / name).read_bytes()
        if not 0 < len(content) <= 65536:
            raise ValueError(f"Source page exceeds bounds: {name}")
        blobs += array("source_" + source_id, content)
    blobs += "inline bool source_page(uint32_t id, const uint8_t **data, std::size_t *size) {\n  switch (id) {\n"
    for source_id in sorted(sources, key=int):
        blobs += f"  case {source_id}: *data = source_{source_id}; *size = sizeof source_{source_id}; return true;\n"
    blobs += "  default: return false;\n  }\n}\n} // namespace remote\n"
    outputs = {
        "proto/flash_settings.proto": proto.encode(),
        "fw/robot_sf/include/remote/catalog.hpp": catalog.encode(),
        "fw/robot_sf/include/remote/settings_bindings.hpp": bindings_header.encode(),
        "generic_field_tool/android/app/src/main/assets/robot.desc": data,
        "fw/robot_sf/include/remote/schema_blob.hpp": (HEADER + "#pragma once\n#include <cstdint>\nnamespace remote {\n" + array("schema_blob", data) + "}\n").encode(),
        "fw/robot_sf/include/remote/source_blob.hpp": blobs.encode(),
    }
    for name in ("telemetry.proto", "remote_config.proto"):
        outputs["fw/telemetry_bridge/proto/" + name] = (root / "proto" / name).read_bytes()
    outputs["fw/telemetry_bridge/proto/flash_settings.proto"] = proto.encode()
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated assets are stale")
    args = parser.parse_args()
    outputs = generate()
    stale = []
    for name, data in outputs.items():
        path = ROOT / name
        if not path.is_file() or path.read_bytes() != data:
            stale.append(name)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    if args.check and stale:
        parser.exit(1, "Stale schema assets:\n" + "\n".join(stale) + "\n")
    print(f"{'Checked' if args.check else 'Generated'} {len(outputs)} schema/catalog assets")


if __name__ == "__main__":
    main()
